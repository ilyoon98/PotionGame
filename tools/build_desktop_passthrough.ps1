$ErrorActionPreference = 'Stop'
$projectDir = Split-Path -Parent $PSScriptRoot
$compilerPath = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path -LiteralPath $compilerPath)) { throw 'Windows .NET Framework 4.x compiler is required to rebuild the input bridge.' }
$sourcePath = Join-Path $projectDir 'native\windows\DesktopPassthrough.cs'
$binaryPath = Join-Path $projectDir 'native\windows\desktop_passthrough.exe'
& $compilerPath /nologo /target:winexe /platform:x64 /optimize+ "/out:$binaryPath" $sourcePath
if ($LASTEXITCODE -ne 0) { throw 'Input bridge compilation failed.' }
$encodedBytes = [Convert]::ToBase64String([IO.File]::ReadAllBytes($binaryPath))
$resourcePath = Join-Path $projectDir 'native\windows\desktop_bridge_binary.gd'
# A preloaded GDScript resource is included by Godot's normal PCK export.
[IO.File]::WriteAllText($resourcePath, "extends RefCounted`n# Generated by tools/build_desktop_passthrough.ps1. Source: DesktopPassthrough.cs.`nconst BASE64 = `"$encodedBytes`"`n", [Text.UTF8Encoding]::new($false))
Get-FileHash -LiteralPath $binaryPath -Algorithm SHA256
