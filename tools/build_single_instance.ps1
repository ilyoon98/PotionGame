$ErrorActionPreference = 'Stop'
$projectDir = Split-Path -Parent $PSScriptRoot
$compilerPath = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path -LiteralPath $compilerPath)) { throw 'Windows .NET Framework compiler is required.' }
$sourcePath = Join-Path $projectDir 'native\windows\SingleInstanceGuard.cs'
$binaryPath = Join-Path $projectDir 'native\windows\single_instance_guard.exe'
& $compilerPath /nologo /target:winexe /platform:x64 /optimize+ "/out:$binaryPath" $sourcePath
if ($LASTEXITCODE -ne 0) { throw 'Single-instance guard compilation failed.' }
$encodedBytes = [Convert]::ToBase64String([IO.File]::ReadAllBytes($binaryPath))
$resourcePath = Join-Path $projectDir 'native\windows\single_instance_binary.gd'
[IO.File]::WriteAllText($resourcePath, "extends RefCounted`n# Generated by tools/build_single_instance.ps1. Source: SingleInstanceGuard.cs.`nconst BASE64 = `"$encodedBytes`"`n", [Text.UTF8Encoding]::new($false))
Get-FileHash -LiteralPath $binaryPath -Algorithm SHA256
$fixtureSource = Join-Path $projectDir 'tools\SingleInstanceFixture.cs'
$fixtureDirectory = Join-Path $projectDir '.verification'
[IO.Directory]::CreateDirectory($fixtureDirectory) | Out-Null
$fixtureBinary = Join-Path $fixtureDirectory 'single-instance-fixture.exe'
& $compilerPath /nologo /target:winexe /platform:x64 /r:System.Web.Extensions.dll "/out:$fixtureBinary" $fixtureSource
if ($LASTEXITCODE -ne 0) { throw 'Single-instance fixture compilation failed.' }
