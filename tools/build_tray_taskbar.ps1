$ErrorActionPreference = 'Stop'
$projectDir = Split-Path -Parent $PSScriptRoot
$compilerPath = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
$sourcePath = Join-Path $projectDir 'native/windows/TrayTaskbar.cs'
$binaryPath = Join-Path $projectDir 'native/windows/tray_taskbar.exe'
& $compilerPath /nologo /target:winexe /platform:x64 /optimize+ "/out:$binaryPath" $sourcePath
if ($LASTEXITCODE -ne 0) { throw 'Tray taskbar helper compilation failed.' }
$bytes = [Convert]::ToBase64String([IO.File]::ReadAllBytes($binaryPath))
$resourcePath = Join-Path $projectDir 'native/windows/tray_taskbar_binary.gd'
[IO.File]::WriteAllText($resourcePath,"extends RefCounted`n# Generated by tools/build_tray_taskbar.ps1. Source: TrayTaskbar.cs.`nconst BASE64 = `"$bytes`"`n",[Text.UTF8Encoding]::new($false))
Get-FileHash -LiteralPath $binaryPath -Algorithm SHA256
